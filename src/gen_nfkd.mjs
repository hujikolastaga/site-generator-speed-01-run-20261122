rs += `    match NFKD_MAP.binary_search_by_key(&cp, |e| e.cp) {\n`;
rs += `        Ok(i) => {\n`;
rs += `            let e = NFKD_MAP[i];\n`;
rs += `            let off = e.off as usize;\n`;
rs += `            Some((e.flags, &NFKD_POOL[off..off + e.len as usize]))\n`;
rs += `        }\n`;
rs += `        Err(_) => None,\n`;
