// Generates exact Node 22 NFKD slugify lookup tables for all Unicode codepoints >= 0x80.
// Matches vendor/makefun-site/lib/text.js slugify(text):
//   const plain = text.normalize('NFKD').replace(/\p{M}/gu, '');
//   loop for (const ch of plain): keep A-Z->a-z, a-z, 0-9; else gap = out.length > 0; cap 64; strip trailing '-'

function normalizeNonAscii(cp) {
  const s = String.fromCodePoint(cp);
  const plain = s.normalize('NFKD').replace(/\p{M}/gu, '');
  if (plain === '') return { kind: 'empty' };
  let out = '';
  let gap = false;
  let gapBefore = false;
  let emitted = false;
  for (const ch of plain) {
    let keep = null;
    if (ch >= 'A' && ch <= 'Z') keep = ch.toLowerCase();
    else if ((ch >= 'a' && ch <= 'z') || (ch >= '0' && ch <= '9')) keep = ch;
    if (keep === null) {
      if (!emitted) gapBefore = true;
      else gap = true;
    } else {
      if (gap) out += '-';
      gap = false;
      out += keep;
      emitted = true;
    }
  }
  const gapAfter = gap;
  if (!emitted) return { kind: 'gap' };
  return { kind: 'map', out, gapBefore, gapAfter };
}

const emptyRanges = [];
const mapEntries = [];
const pool = [];
let gapCount = 0;

for (let cp = 0x80; cp <= 0x10ffff; cp++) {
  if (cp >= 0xd800 && cp <= 0xdfff) continue;
  const r = normalizeNonAscii(cp);
  if (r.kind === 'empty') {
    if (emptyRanges.length > 0 && emptyRanges[emptyRanges.length - 1][1] + 1 === cp) {
      emptyRanges[emptyRanges.length - 1][1] = cp;
    } else {
      emptyRanges.push([cp, cp]);
    }
  } else if (r.kind === 'map') {
    const bytes = Buffer.from(r.out, 'ascii');
    const off = pool.length;
    for (const b of bytes) pool.push(b);
    const flags = (r.gapBefore ? 1 : 0) | (r.gapAfter ? 2 : 0);
    mapEntries.push({ cp, flags, off, len: bytes.length });
  } else {
    gapCount++;
  }
}

console.log(`NFKD summary: emptyRanges=${emptyRanges.length}, mapEntries=${mapEntries.length}, poolBytes=${pool.length}, gapCount=${gapCount}`);

